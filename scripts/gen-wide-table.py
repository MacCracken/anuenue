# scripts/gen-wide-table.py — regenerate anuenue's wide-character table
# (v1.4.4, ADR 0005).
#
# Prints `_CP_WIDE_COUNT` and `_cp_wide_chunk` for src/animate.cyr: every
# UAX #11 East Asian Width W or F range from U+0080 to U+3FFFF, in Python's
# Unicode version, as 5-hex-digit (lo, hi) pairs, eight ranges to a chunk so
# every line stays inside cyrlint's 120 columns.
# Ranges separated only by unassigned (Cn) or zero-width (Mn / Me / Cf)
# codepoints are merged: an unassigned codepoint never appears in text,
# and a zero-width one never starts a cluster, which is the only place
# anuenue asks for a width.
#
# The table is only as current as the Python that generates it: its
# `unicodedata` carries one Unicode version (3.14: 16.0.0; 3.13: 15.1.0),
# and East Asian Width changes between versions (U+2630..2637 became Wide
# in 16.0). So the header records both the Unicode and the Python version,
# pty-check.sh gate 5 compares strictly only on a Python with the same
# Unicode, and CI installs the Python the header names.
#
# Usage: python3 -I scripts/gen-wide-table.py
# Then paste the output over the block between the GENERATED markers in
# src/animate.cyr, and run
# scripts/pty-check.sh, whose gate 5 compares the result with this same
# oracle codepoint by codepoint.
import sys
import unicodedata as u


def wide(c):
    return u.east_asian_width(chr(c)) in ("W", "F")


def gap_ok(c):
    return u.category(chr(c)) in ("Cn", "Mn", "Me", "Cf")


ranges, start = [], None
for c in range(0x80, 0x40000):
    if wide(c):
        if start is None:
            start = c
    elif start is not None:
        ranges.append([start, c - 1])
        start = None
if start is not None:
    ranges.append([start, 0x3FFFF])

merged = []
for lo, hi in ranges:
    if merged and all(gap_ok(x) for x in range(merged[-1][1] + 1, lo)):
        merged[-1][1] = hi
    else:
        merged.append([lo, hi])

PER = 8
chunks = [merged[k:k + PER] for k in range(0, len(merged), PER)]
print("# GENERATED by scripts/gen-wide-table.py — UAX #11 W / F, Unicode %s, Python %d.%d, %d ranges."
      % (u.unidata_version, sys.version_info[0], sys.version_info[1], len(merged)))
print("var _CP_WIDE_COUNT = %d;" % len(merged))
print("var _CP_WIDE_PER_CHUNK = %d;" % PER)
print("")
print("# The k-th chunk of the table: up to %d (lo, hi) pairs, 10 hex digits each." % PER)
print("fn _cp_wide_chunk(k): i64 {")
for k, ch in enumerate(chunks):
    print('    if (k == %-2d) { return "%s"; }' % (k, "".join("%05X%05X" % (lo, hi) for lo, hi in ch)))
print("    return 0;")
print("}")
print("# END GENERATED")
